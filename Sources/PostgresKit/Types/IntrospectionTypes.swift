        public let referencedColumn: String

        public init(constraintName: String, referencedSchema: String, referencedTable: String, referencedColumn: String) {
            self.constraintName = constraintName
            self.referencedSchema = referencedSchema
            self.referencedTable = referencedTable
            self.referencedColumn = referencedColumn
        }
    }
    public let name: String
    public let dataType: String
    public let isNullable: Bool
    public let maxLength: Int?
    public let isPrimaryKey: Bool
    public let foreignKey: ForeignKeyRef?

    public init(name: String, dataType: String, isNullable: Bool, maxLength: Int?, isPrimaryKey: Bool, foreignKey: ForeignKeyRef?) {
        self.name = name
        self.dataType = dataType
        self.isNullable = isNullable
        self.maxLength = maxLength
        self.isPrimaryKey = isPrimaryKey
        self.foreignKey = foreignKey
    }
}

/// Index information.
public struct PostgresIndexInfo: Sendable {
    public struct Column: Sendable {
        public let name: String
        public let isDescending: Bool
        /// Whether this is an INCLUDE (non-key) column rather than a key column.
        public let isIncluded: Bool

        public init(name: String, isDescending: Bool, isIncluded: Bool = false) {
            self.name = name
            self.isDescending = isDescending
            self.isIncluded = isIncluded
        }
    }
    public let name: String
    public let isUnique: Bool
    public let columns: [Column]
    public let predicate: String?
    /// The index access method (e.g., `"btree"`, `"hash"`, `"gin"`, `"gist"`, `"brin"`).
    public let indexType: String?
    /// False for an index a failed `CREATE INDEX CONCURRENTLY` left behind: it is kept up to
    /// date but not used, until it is rebuilt or dropped.
    public let isValid: Bool

    public init(name: String, isUnique: Bool, columns: [Column], predicate: String?, indexType: String? = nil, isValid: Bool = true) {
        self.name = name
        self.isUnique = isUnique
        self.columns = columns
        self.predicate = predicate
        self.indexType = indexType
        self.isValid = isValid
    }
}

